/* Devolve o <svg> pronto.
   classe: a classe CSS ('ico', 'ico-mini', ...)
   Sem aria: todo ícone deste site é decorativo, e o texto ao lado já diz
   o que ele significa. Ícone com rótulo repetido faz o leitor de tela ler
   a mesma coisa duas vezes. */
function icone(nome, classe) {
  var d = ICONES[nome];
  if (!d) { throw new Error('icone inexistente: ' + nome); }
  return '<svg class="' + (classe || 'ico') + '" viewBox="0 0 24 24" aria-hidden="true" focusable="false">' + d + '</svg>';
}

